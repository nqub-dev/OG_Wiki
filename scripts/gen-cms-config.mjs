#!/usr/bin/env node
/**
 * Generates public/admin/config.yml from wiki.config.ts.
 *
 * The CMS needs to know the repo, branch and content path — exactly the three
 * values that already drive the "Edit this page" links. Generating the file
 * keeps them from drifting apart, which is the usual way a cloned template
 * ends up with an editor pointing at the wrong client's repo.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const config = readFileSync(new URL('../wiki.config.ts', import.meta.url), 'utf8');
const str = (key) => config.match(new RegExp(`^\\s*${key}:\\s*'([^']*)'`, 'm'))?.[1] ?? '';

const repo = str('repo');
const branch = str('branch') || 'main';
const contentPath = str('contentPath') || 'src/content/docs';
const name = str('name') || 'Wiki';

if (!repo || /your-org|your-wiki/.test(repo)) {
  console.log('! gen:cms — `repo` is unset or still a placeholder; writing a disabled config.');
}

const yaml = `# GENERATED by scripts/gen-cms-config.mjs — do not edit by hand.
# Change repo / branch / contentPath in wiki.config.ts and re-run \`npm run gen:cms\`.

backend:
  name: github
  repo: ${repo || 'your-org/your-wiki'}
  branch: ${branch}
  # No base_url on purpose. Sveltia CMS falls back to Netlify's built-in OAuth
  # client when authentication isn't configured explicitly, which is exactly
  # what we want since this site is hosted on Netlify — no Cloudflare Worker,
  # no client secret to manage.
  #
  # If this wiki ever moves off Netlify, deploy sveltia-cms-auth as a Cloudflare
  # Worker and point base_url at it:
  #   base_url: https://sveltia-cms-auth.<subdomain>.workers.dev

# Editors upload images here; Markdown references them from public_folder.
media_folder: public/uploads
public_folder: /uploads

site_url: /
display_url: /
locale: en

collections:
  - name: docs
    label: Wiki pages
    label_singular: page
    folder: ${contentPath}
    create: true
    delete: false
    extension: md
    format: yaml-frontmatter
    slug: '{{slug}}'
    # Mirrors the Zod schema in src/content.config.ts. Keep them in sync —
    # the build fails loudly if the CMS writes a field the schema rejects.
    fields:
      - { name: title, label: Title, widget: string }
      - { name: description, label: Description, widget: text, required: false }
      - { name: icon, label: Icon (emoji), widget: string, default: '📄', required: false }
      - name: section
        label: Section
        widget: select
        options: ['Start Here', 'Handbook', 'Engineering', 'Operations', 'Reference']
      - { name: order, label: Sort order, widget: number, default: 999, value_type: int }
      - { name: tags, label: Tags, widget: list, required: false }
      - name: status
        label: Status
        widget: select
        default: draft
        options: [draft, review, stable, deprecated]
      - { name: updated, label: Last updated, widget: datetime, format: 'YYYY-MM-DD', required: false }
      - { name: owner, label: Owner, widget: string, required: false }
      - { name: draft, label: Hide from the published site, widget: boolean, default: false }
      - { name: featured, label: Feature on the home page, widget: boolean, default: false }
      - { name: body, label: Page content, widget: markdown }
`;

writeFileSync(new URL('../public/admin/config.yml', import.meta.url), yaml);
console.log(`✓ gen:cms — public/admin/config.yml → ${repo || '(unset)'}@${branch}/${contentPath}`);
