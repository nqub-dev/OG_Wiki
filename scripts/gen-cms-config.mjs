#!/usr/bin/env node
/**
 * Generates public/admin/config.yml from wiki.config.ts + the folders that
 * actually exist under src/content/docs/.
 *
 * Why one collection per section folder, rather than a single collection
 * pointing at src/content/docs:
 *
 *   Folder collections in Decap/Sveltia do not recurse into subdirectories.
 *   A single `folder: src/content/docs` would list ZERO pages, because every
 *   page lives in a section subfolder. Sveltia's nested-collection support is
 *   slated for 2.0 and still beta, so relying on it would be fragile.
 *
 *   Generating one flat collection per folder sidesteps that entirely, and the
 *   CMS sidebar ends up mirroring the wiki's own section structure — which is
 *   the better UI anyway. It also lets us pin `section` per collection so a
 *   page's frontmatter can never disagree with the folder it lives in.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const config = readFileSync(join(root, 'wiki.config.ts'), 'utf8');
const str = (key) => config.match(new RegExp(`^\\s*${key}:\\s*'([^']*)'`, 'm'))?.[1] ?? '';

const repo = str('repo');
const branch = str('branch') || 'main';
const contentPath = str('contentPath') || 'src/content/docs';
const docsDir = join(root, contentPath);

if (!repo || /your-org|your-wiki/.test(repo)) {
  console.log('! gen:cms — `repo` is unset or still a placeholder; the CMS will not be able to sign in.');
}

/** Human label for a folder: take it from the `section` of a page inside it. */
function labelFor(dir) {
  const files = readdirSync(join(docsDir, dir)).filter((f) => /\.mdx?$/.test(f));
  for (const file of files) {
    const src = readFileSync(join(docsDir, dir, file), 'utf8');
    const fm = src.match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1];
    const section = fm?.match(/^section:\s*(.+)$/m)?.[1]?.trim().replace(/^["']|["']$/g, '');
    if (section) return section;
  }
  // No page declares one yet — title-case the folder name.
  return dir.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

const folders = readdirSync(docsDir).filter((d) => statSync(join(docsDir, d)).isDirectory());

const collections = folders
  .map((dir) => {
    const label = labelFor(dir);
    return `  - name: ${dir}
    label: ${JSON.stringify(label)}
    label_singular: page
    folder: ${contentPath}/${dir}
    create: true
    delete: true
    extension: md
    format: yaml-frontmatter
    slug: '{{slug}}'
    summary: '{{title}}'
    sortable_fields: [order, title, updated]
    # Mirrors the Zod schema in src/content.config.ts. If these drift apart the
    # build fails loudly rather than publishing a broken page.
    fields:
      - { name: title, label: Title, widget: string }
      - { name: description, label: Description, widget: text, required: false }
      - { name: icon, label: Icon (emoji), widget: string, default: '📄', required: false }
      # Pinned to this folder so frontmatter can't disagree with location.
      - { name: section, label: Section, widget: hidden, default: ${JSON.stringify(label)} }
      - { name: order, label: Sort order, widget: number, default: 999, value_type: int }
      - { name: tags, label: Tags, widget: list, required: false }
      - name: status
        label: Status
        widget: select
        default: draft
        options: [draft, review, stable, deprecated]
      - {
          name: updated,
          label: Last updated,
          widget: datetime,
          format: 'YYYY-MM-DD',
          date_format: 'YYYY-MM-DD',
          time_format: false,
          required: false,
        }
      - { name: owner, label: Owner, widget: string, required: false }
      - { name: draft, label: Hide from the published site, widget: boolean, default: false }
      - { name: featured, label: Feature on the home page, widget: boolean, default: false }
      - { name: body, label: Page content, widget: markdown }`;
  })
  .join('\n\n');

const yaml = `# GENERATED by scripts/gen-cms-config.mjs — do not edit by hand.
# Runs automatically as part of \`npm run build\`.
# To change it: edit wiki.config.ts or add a folder under ${contentPath}/,
# then \`npm run gen:cms\`.

backend:
  name: github
  repo: ${repo || 'your-org/your-wiki'}
  branch: ${branch}
  # No base_url on purpose. Sveltia CMS falls back to Netlify's built-in OAuth
  # client when authentication isn't configured explicitly, which is what we
  # want on Netlify — no Cloudflare Worker, no client secret in the repo.
  #
  # If this wiki moves off Netlify, deploy sveltia-cms-auth as a Cloudflare
  # Worker and point base_url at it:
  #   base_url: https://sveltia-cms-auth.<subdomain>.workers.dev

# Editors drop images here; Markdown references them via public_folder.
media_folder: public/uploads
public_folder: /uploads

locale: en

collections:
${collections}
`;

writeFileSync(join(root, 'public/admin/config.yml'), yaml);
console.log(
  `✓ gen:cms — ${folders.length} collections (${folders.join(', ')}) → ${repo || '(unset)'}@${branch}`,
);
